N = 10


def ep(n, name, hook, scene, prop, amb, V, A, voices, lines, **kw):
    d = _sk("s2-%02d" % n, "Gérard · Saison 2 · Épisode %d" % n, hook, scene, prop, amb, dict(E=GERARD, V=V, A=A),
            ("miro",) + voices, lines, cta_title="Suis Gérard !",
            cta_sub="Épisode %d demain" % (n + 1) if n < N else "La saison 3 arrive", **kw)
    d["slug"] = "s2-%02d-%s" % (n, name)
    if d["voices"]["A"][0] == d["voices"]["V"][0]:  # même voix : l'autorité parle plus grave et plus posément
        d["voices"]["A"] = (d["voices"]["A"][0], 0.94, -2.5)
    return d


