from sketches import P, SKIN


def sk(slug, title, hook, scene, prop, amb, cast, voices, lines, **kw):
    lines = list(lines)
    mid_i = next(i for i, l in enumerate(lines) if len(l) > 3 and l[3] == "MID")
    mid = lines.pop(mid_i)
    enter_i = next(i for i, l in enumerate(lines) if l[0] == "@ENTER")
    lines.insert(enter_i + 3, mid)   # après l'arrivée de l'autorité et la plainte de l'exigeant (~45-50 %)
    d = dict(slug="s4-" + slug, title=title, hook_text=hook, scene=scene, prop=prop, ambience=amb, cast=cast,
             voices=dict(zip("EVA", [(v, 1.0, 0.0) for v in voices])), lines=lines, cta=True, cta_dy=-120,
             caption_y=1440, voice_mode="fr")
    d.update(kw)
    return d


def L(*rows):
    out = []
    for r in rows:
        if r.startswith("@"):
            out.append((r,))
        elif r[3:].startswith("§"):
            out.append((r[0], r[1], r[4:], "MID"))
        else:
            out.append((r[0], r[1], r[3:]))
    return out


